export function generateSampleCriteria(seed: number, isHigh: boolean = false, subject: string = '', teacherName: string = ''): CriterionResult[] {
  const subLower = (subject || '').toLowerCase();
  const domain: 'math' | 'physics' | 'cs' | 'general' = subLower.includes('физик') ? 'physics'
    : (subLower.includes('информ') || subLower.includes('программ') || subLower.includes('код') || subLower.includes('it') || subLower.includes('алгоритм')) ? 'cs'
    : (subLower.includes('мат') || subLower.includes('геом') || subLower.includes('алгебр')) ? 'math'
    : 'general';

  // Разнообразные педагогические профили заметок:
  // Каждый учитель, предмет и сид дают индивидуальный набор сильных и слабых сторон
  const hash = Math.abs((seed ^ 15485863) + teacherName.split('').reduce((acc, c) => acc + c.charCodeAt(0) * 17, 0) + subject.length * 31);
  
  const possibleRemarksProfiles = [
    [5, 8],          // Тайминг + эмпатия к отстающим
    [2, 7, 18],      // Подготовка интерактивной доски + вовлечение всей группы + размер шрифта
    [6, 11],         // Интерактивность опроса + дифференциация сильных/слабых
    [4, 12, 17],     // Мотивированность переходов + баланс теории и практики + переключение окон
    [1, 10],         // Уверенность разбора + педагогический тон
    [3, 14, 16],     // Озвучивание целей + пунктуальность начала + качество микрофона
    [9, 13],         // Работа с ошибками + глубина подачи материала
    [8, 15],         // Отслеживание реакции класса + завершение без превышения времени
    [7, 11, 13],     // Работа со всем классом + нагрузка для сильных + глубина
    [],              // Безупречный эталонный урок (100% пройдено, оценка 98-100)
    [16, 17, 19],    // Технические нюансы (звук, окна, сбои)
    [10, 20]         // Психологический климат + демонстрация лишних вкладок
  ];

  const profileIndex = hash % possibleRemarksProfiles.length;
  const rawFailed = possibleRemarksProfiles[profileIndex];
  
  // Если задан флаг высокой оценки — оставляем не более 1 замечания
  const failedIndices = isHigh 
    ? (rawFailed.length > 0 ? [rawFailed[0]] : [])
    : rawFailed;

  return STANDARD_CRITERIA_LIST.map((c, i) => {
    const isFailed = failedIndices.includes(c.id);
    const metric = CRITERIA_METRICS[c.id];

    // Динамический сдвиг таймкодов в зависимости от урока (уникальные минуты и секунды)
    const minuteShift = (hash + i * 4) % 22;
    const secondShift = (hash * 13 + i * 19) % 55;
    const formatTime = (baseMin: number) => {
      const totalMin = Math.min(88, Math.max(1, baseMin + minuteShift));
      const hours = Math.floor(totalMin / 60).toString().padStart(2, '0');
      const mins = (totalMin % 60).toString().padStart(2, '0');
      const secs = secondShift.toString().padStart(2, '0');
      return `${hours}:${mins}:${secs}`;
    };

    let comment = isFailed ? metric.failedComment : metric.passedComment;
    let quote = isFailed ? metric.failedQuote : metric.passedQuote;
    const timecodes = isFailed 
      ? [formatTime(14 + i * 2), formatTime(42 + i * 2)]
      : [formatTime(6 + i * 3)];

    // Подставляем глубокую предметную специфику для критериев с профилями
    if (SUBJECT_SPECIFICS[c.id]?.[domain]) {
      const spec = SUBJECT_SPECIFICS[c.id][domain];
      if (isFailed) {
        comment = `Зафиксировано затруднение в процессе: ${spec.term}. Преподавателю рекомендовано обратить внимание на данный аспект.`;
        quote = spec.quoteBad;
      } else {
        comment = `Преподаватель образцово реализовал ${spec.term}: глубокая предметная подача без методических погрешностей.`;
        quote = spec.quoteGood;
      }
    }

    const passed = !isFailed;
    // Оценка критерия (1..5)
    const score = passed 
      ? (isHigh ? 5 : ((hash + i) % 5 === 0 ? 4 : 5))
      : Math.max(1, 3 - ((hash + i) % 2));

    return {
      id: c.id,
      text: c.text,
      category: c.category,
      passed,
      score,
      timecodes,
      comment,
      quote
    };
  });
}

const SEED_TASKS: LectureCheck[] = [];

function ensureDataDir() {
  if (!fs.existsSync(DATA_DIR)) {
    fs.mkdirSync(DATA_DIR, { recursive: true });
  }
}

export function loadTasks(): LectureCheck[] {
  ensureDataDir();
  if (!fs.existsSync(TASKS_FILE)) {
    fs.writeFileSync(TASKS_FILE, JSON.stringify(SEED_TASKS, null, 2), 'utf-8');
    return SEED_TASKS;
  }
  try {
    const raw = fs.readFileSync(TASKS_FILE, 'utf-8');
    return JSON.parse(raw);
  } catch (err) {
    console.error('Ошибка чтения lecture_tasks.json:', err);
    return SEED_TASKS;
  }
}

export function saveTasks(tasks: LectureCheck[]) {
  ensureDataDir();
  fs.writeFileSync(TASKS_FILE, JSON.stringify(tasks, null, 2), 'utf-8');
}

export function getTeachersList(): string[] {
  const tasks = loadTasks();
  const teachers = new Set<string>(INITIAL_TEACHERS);
  tasks.forEach(t => {
    if (t.teacherName) teachers.add(t.teacherName);
  });
  return Array.from(teachers);
}

export function createTask(
  lectureUrl: string,
  teacherName: string,
  subject: string,
  groupName: string,
  curatorEmail: string
): LectureCheck {
  const tasks = loadTasks();
  const id = `lec_${Date.now()}`;
  
  const newTask: LectureCheck = {
    id,
    lectureUrl: lectureUrl.trim(),
    teacherName: teacherName.trim(),
    subject: subject.trim() || 'Олимпиадная подготовка',
    groupName: groupName.trim() || 'Основная группа',
    date: new Date().toISOString().replace('T', ' ').slice(0, 16),
    totalScore: 0,
    criticalViolations: [],
    positiveHighlights: [],
    recommendations: [],
    criteria: STANDARD_CRITERIA_LIST.map(c => ({
      id: c.id,
      text: c.text,
      category: c.category,
      passed: true,
      score: 5
    })),
    status: 'downloading',
    progressPct: 15,
    curatorEmail,
    createdAt: new Date().toISOString()
  };

  tasks.unshift(newTask);
  saveTasks(tasks);

  // Симулируем реалистичное продвижение этапов анализа (КТалк -> ffmpeg -> GigaChat)
  simulateTaskProgress(id);

  return newTask;
}

function simulateTaskProgress(taskId: string) {
  const steps = [
    { delay: 3000, status: 'downloading' as const, pct: 35 },
    { delay: 7000, status: 'extracting' as const, pct: 65 },
    { delay: 12000, status: 'analyzing' as const, pct: 85 },
    { delay: 18000, status: 'completed' as const, pct: 100 }
  ];

  steps.forEach(step => {
    setTimeout(() => {
      const tasks = loadTasks();
      const task = tasks.find(t => t.id === taskId);
      if (!task) return;

      task.status = step.status;
      task.progressPct = step.pct;

      if (step.status === 'completed') {
        const criteria = generateSampleCriteria(Date.now(), false, task.subject, task.teacherName);
        const failedCriteria = criteria.filter(c => !c.passed);
        const passedCriteria = criteria.filter(c => c.passed);

        // Расчет итогового балла из суммы баллов по критериям (0..100)
        const maxPoints = criteria.length * 5;
        const earnedPoints = criteria.reduce((sum, c) => sum + (c.score || 0), 0);
        const score = Math.min(100, Math.max(60, Math.round((earnedPoints / maxPoints) * 100)));

        task.totalScore = score;
        task.positiveHighlights = passedCriteria.slice(0, 3).map(c => c.comment || c.text);
        task.recommendations = failedCriteria.length > 0
          ? failedCriteria.map(c => `По критерию «${c.category}» (№${c.id}): ${c.comment}`)
          : ["Занятие проведено на высочайшем методическом уровне, критических замечаний нет."];
        task.criteria = criteria;
      }

      saveTasks(tasks);
    }, step.delay);
  });
}
